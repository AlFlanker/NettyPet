package dev.example.resilience;

import java.util.concurrent.CompletionStage;

/** Запущенная операция и кооперативная отмена её ресурсов. */
public interface CommandTask<T> {
    /**
     * Стабильный ненулевой stage, завершающийся только после освобождения всех ресурсов.
     * Метод не блокируется и не бросает исключений; повторные вызовы возвращают тот же stage.
     */
    CompletionStage<T> completion();

    /**
     * Неблокирующий потокобезопасный сигнал отмены, не бросающий исключений.
     * После сигнала completion() обязан завершиться, когда очистка действительно закончится.
     * Если операция уже закончилась, сигнал ничего не делает.
     */
    void cancel(CancellationReason reason);
}
