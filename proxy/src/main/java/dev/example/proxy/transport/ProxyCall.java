package dev.example.proxy.transport;

import dev.example.proxy.api.ProxyResult;
import java.util.concurrent.CompletionStage;

/** Управление одним потоковым обменом независимо от библиотеки, ограничивающей выполнение команд. */
public interface ProxyCall {
    /**
     * Возвращает CompletionStage с результатом. Он завершается только после окончания
     * обмена и всех этапов очистки: освобождения буферов, обработки результата получения
     * канала, его возврата или закрытия, возврата слота допуска и попытки завершить
     * либо прервать Servlet-ответ.
     * Представление доступно только для чтения; отмена его CompletableFuture не отменяет обмен.
     * Подписанные обработчики могут выполняться в потоке I/O и не должны блокировать его.
     */
    CompletionStage<ProxyResult> completion();

    /**
     * Ставит запрос отмены в закреплённый цикл событий, не ожидая сетевых операций.
     * status должен быть в диапазоне 400..599. До отправки заголовков клиенту можно
     * выставить этот статус; после их отправки ответ прерывается. Повторная отмена
     * и отмена завершённого обмена ничего не меняют; очистку подтверждает completion().
     */
    void cancel(int status);
}
